create role anon nologin; create role authenticated nologin; create role service_role nologin bypassrls;
create schema auth;
create table auth.users (id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
create function auth.role() returns text language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claim.role', true), ''), current_user::text) $$;
grant usage on schema auth, public to anon, authenticated, service_role;
grant execute on all functions in schema auth to anon, authenticated, service_role;

create table public.profiles (id uuid primary key references auth.users(id), handle text, skills jsonb);
create table public.opportunities (id bigint generated by default as identity primary key, poster_id uuid, poster_handle text, title text, description text, category text, created_at timestamptz default now());
create table public.nexar_subscriptions (user_id uuid primary key references auth.users(id), status text, current_period_end timestamptz);
create table public.nexar_pipeline (
  id uuid primary key default gen_random_uuid(), user_id uuid not null references auth.users(id) on delete cascade,
  handle text not null, title text not null, company text not null,
  status text not null default 'Applied' check (status = any (array['Applied','Responded','Interview','Offered','Rejected'])),
  notes text default '', created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table public.nexar_pending_actions (
  id uuid primary key default gen_random_uuid(), user_id uuid not null references auth.users(id) on delete cascade,
  action_type text not null check (action_type = 'delete_pipeline'), target_id uuid not null, preview text not null,
  created_at timestamptz not null default now(), expires_at timestamptz not null default (now() + interval '10 minutes'), consumed_at timestamptz);
create table public.nexar_matches (id uuid primary key default gen_random_uuid(), user_id uuid not null, handle text not null, opportunity_id bigint not null references public.opportunities(id) on delete cascade, score numeric not null, match_reason text, status text not null default 'new', unique (user_id, opportunity_id));
create table public.nexar_reminders (id uuid primary key default gen_random_uuid(), user_id uuid not null, pipeline_id uuid, kind text not null, message text not null, match_id uuid, dismissed_at timestamptz);

create function public.nexar_pipeline_touch() returns trigger language plpgsql as $$ begin new.updated_at = clock_timestamp(); return new; end $$;
create trigger nexar_pipeline_touch_trg before update on public.nexar_pipeline for each row execute function public.nexar_pipeline_touch();

CREATE OR REPLACE FUNCTION public.nexar_effective_status(uid uuid)
 RETURNS text LANGUAGE sql SECURITY DEFINER SET search_path TO 'pg_catalog', 'pg_temp'
AS $function$
  select case
    when ns.status in ('active', 'trialing')
      and (ns.current_period_end is null or ns.current_period_end > pg_catalog.now())
      then ns.status
    when ns.status in ('active', 'trialing')
      and ns.current_period_end <= pg_catalog.now()
      then 'expired'
    when ns.user_id is null then 'free'
    else ns.status
  end
  from public.nexar_subscriptions ns
  where ns.user_id = uid
    and (auth.uid() = uid or auth.role() = 'service_role')
  union all
  select 'free'
  where (auth.uid() = uid or auth.role() = 'service_role')
    and not exists (select 1 from public.nexar_subscriptions ns where ns.user_id = uid)
  limit 1;
$function$;

create function public.match_opportunity_to_users(p_opp_id bigint) returns integer language plpgsql security definer set search_path to 'public','pg_temp' as $$
declare n int; begin
  with ins as (insert into public.nexar_matches (user_id, handle, opportunity_id, score, match_reason)
    select p.id, p.handle, p_opp_id, 1, 'stand-in' from public.profiles p
    where p.id is distinct from (select poster_id from public.opportunities where id = p_opp_id)
    on conflict (user_id, opportunity_id) do nothing returning id, user_id)
  insert into public.nexar_reminders (user_id, kind, message, match_id) select user_id, 'opportunity_match', 'New match', id from ins;
  get diagnostics n = row_count; return n; end $$;
create function public.trg_match_new_opportunity() returns trigger language plpgsql security definer set search_path to 'public','pg_temp' as $$ begin perform public.match_opportunity_to_users(new.id); return new; end $$;
create trigger nexar_match_on_opp_insert after insert on public.opportunities for each row execute function public.trg_match_new_opportunity();
create function public.generate_pipeline_reminders() returns table(kind text, inserted integer) language plpgsql security definer set search_path to 'public','pg_temp' as $$ begin return query values ('stale_applied'::text, 0); end $$;

